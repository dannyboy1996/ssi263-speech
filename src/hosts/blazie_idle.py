"""The Braille Lite's idle channel as Tomi's unit sounds, for the Blazie emulator (src/csrc/blazie/bl_idle.c; the
screen-reader drivers keep hosts/blazie.py's WHINE_TONES).  Measured on the W03 grid (every volume 0-15 x tone 0-26,
"Readme for Microsoft Windows." then 11 s of idle, 96 kHz, unit on battery) by tools/idle_sounds.py; its `fit`
prints these numbers.  gen_idle.py turns them into bl_idle_table.h.

Every level is re REF, the unit's loud vowel at volume 6 (tones 5-9: -12.2 dBFS on the capture): amplitudes as a
ratio to its RMS, lines and noise densities in dB re its mean square.  The C host scales them by its own volume-6
vowel, REF_RMS (the same measure on the emulated unit, tones 5-9, after the board pole).

What the unit does (the emulated firmware, watched: port A0 bit 1 is the speech channel's power):
  - opening: a line after the channel was clicked off sets A0 bit 1 and writes R3 = 80, 70, then 5x (x = the volume)
    ~0.26 s before its first phoneme; the recording's pop comes 0.27-0.31 s before the next line's acoustic onset.
  - the click-off: R3 = 00 and A0 bit 1 off together, from the firmware's 10 Hz timer ~10.3 s after the last phoneme
    load (10.19 s after the acoustic end, emulated; 10.22 s on the unit, IQR 10.19-10.24, 327 cells).
  - the volume is R3's low nibble (R3 = 50h + volume); nothing below depends on it.

The sounds:
  NOISE  the open channel's broadband noise: a plateau density (dB re REF^2 per Hz) through two first-order poles.
         20 dB over the closed channel from 16 Hz to 1.5 kHz; -47 dB re REF in 60 Hz-10 kHz at EVERY volume (the
         hiss does not fall with the volume: -46.3 to -47.3 dB over volumes 0-15), so at volume 1 it sits 29 dB
         under that volume's vowel and at volume 15 50 dB under.  Fit residual 0.7 dB rms (25 Hz-4.5 kHz).
  LINES  the comb lines n x fc/64 over that noise, per class (even volumes = hiss, odd = whine) and tone: the median
         over the class's volumes 1-15 of each cell's absolute level (dB re REF's mean square), kept where the line
         shows in at least half of them.  (WHINE_TONES used each cell's own vowel as reference, so it put the lines of
         a louder volume's cells lower; and it has no noise, the idle's larger part.)
  POP    when the channel opens: a step through two first-order high-passes plus a fast spike -- (step, tau1, tau2,
         spike, spike tau), step and spike re REF's RMS.  +0.87 FS on the capture at every volume 0-9, 14, 15.
  CLICK  when the channel is clicked off: a step through two high-passes -- (step, tau1, tau2).  -0.53 FS at every
         volume.  Both shapes are the unit's output coupling AND the capture's line-in, which cannot be told apart
         here: what a listener hears on the unit's headphones decays faster.
  TICK   while the channel is open, every TICK_PERIOD_S (the firmware's 10 Hz timer, as captured): the timer-aligned
         average of the open idle (the click-off, written by that timer, gives the phase), at 24 kHz, re REF's RMS,
         from 1 ms before its first edge; its first edge leads the click-off edge's phase by 0.7 ms (TICK_LEAD_S is
         the template start to that phase).  -0.80 mFS peak (-48 dB re REF), about 13 dB under the noise's RMS in its
         own 2 ms: heard as a rhythm more than as a sound.  Gone after the click-off (-0.09 mFS in the same fold).

Left out: W03's last ~25 minutes (volumes 12-14 there): the volume-1 anchor cells show the unit changing from ~78 min
(the tick 10x, the noise +12 dB), a drift, not a volume effect; W03b/W03c, recorded after it, are back to normal.
An empirical model of the recorded output, not a traced circuit.
"""

